# Dicionário trabalha com KEYS and VALUES, sendo 'nome' a KEY e 'Ana' o VALUE no exemplo a seguir:
aluno = {'nome': 'Ana', 'idade': 16, 'nota_final': 8.6, 'aprovação': True}

print(aluno)                # Imprimindo o dicionário inteiro.
print(aluno['nome'])        # Aqui eu to chamando a KEY 'nome' e ta sendo impresso seu VALUE (valor), no caso Ana.
print(aluno['idade'])       #E assim segue todos os exemplos a baixo
print(aluno['nota_final'])
print(aluno['aprovação'])   # Eu poderia colocar uma string aprovado, mas é só pra mostrar que aceita boolean